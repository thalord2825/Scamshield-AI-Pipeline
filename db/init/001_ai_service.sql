-- PostgreSQL schema corresponding to ScamShield_App/docs/database/ai-service.dbml.
-- Used by the official Postgres image on first initialization of its data volume.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE SEQUENCE IF NOT EXISTS ai_service_generated_core_check_id_seq;

CREATE TABLE IF NOT EXISTS ai_jobs (
    id uuid PRIMARY KEY,
    core_check_id bigint NOT NULL UNIQUE DEFAULT -nextval('ai_service_generated_core_check_id_seq'),
    input_type varchar(30) NOT NULL,
    input_hash varchar(255),
    masked_input text NOT NULL,
    status varchar(30) NOT NULL,
    verdict varchar(30),
    decided_by_stage varchar(30),
    category_code varchar(50),
    confidence decimal(6,5),
    explanation text,
    safety_guidance text,
    unknown_reason varchar(50),
    error_code varchar(100),
    created_at timestamp NOT NULL,
    started_at timestamp,
    completed_at timestamp,
    retention_expires_at timestamp
);
CREATE INDEX IF NOT EXISTS ai_jobs_status_created_at_idx ON ai_jobs (status, created_at);
CREATE INDEX IF NOT EXISTS ai_jobs_input_hash_idx ON ai_jobs (input_hash);

CREATE TABLE IF NOT EXISTS ai_models (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name varchar(150) NOT NULL,
    model_type varchar(50) NOT NULL,
    provider varchar(100),
    version varchar(100) NOT NULL,
    model_uri varchar(500),
    is_active boolean NOT NULL DEFAULT false,
    is_frozen boolean NOT NULL DEFAULT false,
    created_at timestamp NOT NULL,
    UNIQUE (model_name, version)
);

CREATE TABLE IF NOT EXISTS classifier_configs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id bigint NOT NULL REFERENCES ai_models(id),
    low_threshold decimal(6,5) NOT NULL,
    high_threshold decimal(6,5) NOT NULL,
    temperature decimal(8,5),
    class_weight_alpha decimal(6,3),
    training_dataset_version varchar(100),
    configuration_version int NOT NULL,
    is_active boolean NOT NULL DEFAULT false,
    is_frozen boolean NOT NULL DEFAULT false,
    created_by_core_user_id bigint,
    created_at timestamp NOT NULL,
    updated_at timestamp,
    UNIQUE (model_id, configuration_version)
);

CREATE TABLE IF NOT EXISTS prompt_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    version varchar(50) NOT NULL,
    task_type varchar(50) NOT NULL,
    prompt_template text NOT NULL,
    output_schema json,
    is_active boolean NOT NULL DEFAULT false,
    is_frozen boolean NOT NULL DEFAULT false,
    created_by_core_user_id bigint,
    created_at timestamp NOT NULL,
    UNIQUE (name, version)
);

CREATE TABLE IF NOT EXISTS ai_inferences (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ai_job_id uuid NOT NULL REFERENCES ai_jobs(id),
    stage varchar(30) NOT NULL,
    model_id bigint NOT NULL REFERENCES ai_models(id),
    classifier_config_id bigint REFERENCES classifier_configs(id),
    prompt_version_id bigint REFERENCES prompt_versions(id),
    result varchar(30) NOT NULL,
    category_code varchar(50),
    confidence decimal(6,5),
    escalation_reason varchar(50),
    explanation text,
    rendered_prompt text,
    raw_response json,
    attempt_no int NOT NULL DEFAULT 1,
    latency_ms int,
    prompt_tokens int,
    completion_tokens int,
    api_cost decimal(12,6),
    fallback_used boolean NOT NULL DEFAULT false,
    error_code varchar(100),
    created_at timestamp NOT NULL,
    UNIQUE (ai_job_id, stage, attempt_no)
);
CREATE INDEX IF NOT EXISTS ai_inferences_stage_result_idx ON ai_inferences (stage, result);

CREATE TABLE IF NOT EXISTS rag_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_key varchar(200) NOT NULL UNIQUE,
    title varchar(500) NOT NULL,
    source_type varchar(40) NOT NULL,
    source_name varchar(255),
    source_url varchar(1000),
    source_version varchar(100),
    language_code varchar(12) NOT NULL DEFAULT 'vi',
    category_code varchar(50),
    case_label varchar(30),
    review_status varchar(30) NOT NULL,
    content_hash varchar(128) NOT NULL,
    effective_at timestamp,
    expires_at timestamp,
    ingested_at timestamp NOT NULL,
    reviewed_at timestamp,
    created_at timestamp NOT NULL,
    updated_at timestamp
);
CREATE INDEX IF NOT EXISTS rag_documents_review_source_idx ON rag_documents (review_status, source_type);
CREATE INDEX IF NOT EXISTS rag_documents_category_language_idx ON rag_documents (category_code, language_code);
CREATE INDEX IF NOT EXISTS rag_documents_content_hash_idx ON rag_documents (content_hash);

CREATE TABLE IF NOT EXISTS rag_chunks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES rag_documents(id),
    chunk_no int NOT NULL,
    chunk_text text NOT NULL,
    chunk_hash varchar(128) NOT NULL,
    embedding vector,
    embedding_model varchar(150) NOT NULL,
    embedding_version varchar(100) NOT NULL,
    token_count int,
    metadata json,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL,
    UNIQUE (document_id, chunk_no)
);
CREATE INDEX IF NOT EXISTS rag_chunks_chunk_hash_idx ON rag_chunks (chunk_hash);
CREATE INDEX IF NOT EXISTS rag_chunks_active_model_idx ON rag_chunks (is_active, embedding_model, embedding_version);

CREATE TABLE IF NOT EXISTS inference_retrieved_chunks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inference_id bigint NOT NULL REFERENCES ai_inferences(id),
    chunk_id bigint NOT NULL REFERENCES rag_chunks(id),
    retrieval_rank int NOT NULL,
    similarity_score decimal(8,7),
    retrieval_method varchar(30) NOT NULL,
    used_in_prompt boolean NOT NULL DEFAULT true,
    retrieved_at timestamp NOT NULL,
    UNIQUE (inference_id, retrieval_rank),
    UNIQUE (inference_id, chunk_id)
);
CREATE INDEX IF NOT EXISTS inference_retrieved_chunks_chunk_id_idx ON inference_retrieved_chunks (chunk_id);
